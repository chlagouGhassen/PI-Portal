# Lecture des données
# =========================
df_annual = pd.read_excel(
    FILE_FINANCIER,
    sheet_name=SHEET_FINANCIER
)

# =========================
# Conversion des colonnes numériques
# =========================
for col in df_annual.columns:
    if col != "Année":
        df_annual[col] = pd.to_numeric(
            df_annual[col],
            errors="coerce"
        )

# =========================
# Nettoyage et préparation
# =========================
df_annual["Année"] = pd.to_numeric(
    df_annual["Année"],
    errors="coerce"
)

# Suppression des lignes avec années manquantes
df_annual = df_annual.dropna(subset=["Année"])

# Conversion en entier
df_annual["Année"] = df_annual["Année"].astype(int)

# Tri chronologique
df_annual = df_annual.sort_values(
    by="Année"
).reset_index(drop=True)

# =========================
# Informations générales
# =========================
print(f"Années disponibles : {df_annual['Année'].tolist()}")
print(f"Dimensions         : {df_annual.shape}")

print("\nAperçu des données :")
print(df_annual.head())

print("\n✅ Données chargées avec succès")

"""### matrice de correlation des donnees"""

plt.figure(figsize=(20,15))
sns.heatmap(df_annual.select_dtypes(include=['int64','float64',"bool"]).corr(),
            annot=True, cmap='coolwarm')
plt.title("Matrice de corrélation")
plt.show()

"""---
## 2️⃣ EDA — Analyse Exploratoire
"""

# Statistiques descriptives du CA
stats = df_annual[TARGET].describe()
print('📊 Statistiques du Chiffre d\'Affaires')
print(f'  Min      : {df_annual[TARGET].min():>12,.0f} DT')
print(f'  Max      : {df_annual[TARGET].max():>12,.0f} DT')
print(f'  Moyenne  : {df_annual[TARGET].mean():>12,.0f} DT')
print(f'  Médiane  : {df_annual[TARGET].median():>12,.0f} DT')
print(f'  Écart-t  : {df_annual[TARGET].std():>12,.0f} DT')

# Évolution temporelle du CA
fig, ax = plt.subplots(figsize=(10, 4), facecolor=LIGHT)
